import assert from 'node:assert/strict';
import {moments,recencyWeights,weightedForecast,estimateOwnership,ownershipSignal} from '../lib/nba/forecast.mjs';
import {optimize} from '../lib/nba/model.mjs';
import {survivalRecommendation} from '../lib/nba/survival.mjs';
const logs=[{dateCN:'2026-11-23',min:30,score:40},{dateCN:'2026-11-09',min:20,score:20},{dateCN:'2026-10-26',min:10,score:10}];
const w=recencyWeights(logs,'2026-11-24');assert.ok(Math.abs(w[0]/w[1]-2)<1e-10);
assert.equal(moments([10,20,30],[1,1,1]).variance,100);
assert.equal(moments([10],[1]).effectiveN,1);
const forecast=weightedForecast(logs,[],'2026-11-24',g=>g.score,g=>g.score);
const reversed=logs.map((g,i)=>({...g,score:logs[2-i].score,min:logs[2-i].min}));
assert.ok(forecast.baseline>weightedForecast(reversed,[],'2026-11-24',g=>g.score,g=>g.score).baseline);
assert.ok(forecast.effectiveN<3&&forecast.sd>=8);
for(const a of [[],logs.slice(0,1)])assert.ok(Number.isFinite(weightedForecast(a,[],'2026-11-24',g=>g.score,g=>g.score).sd));
const rows=Array.from({length:12},(_,i)=>({id:String(i),position:i<6?'front':'back',energy:15+i*3,average:25,expected:25+i,sd:8+i%4,availability:1,value:(25+i)/(15+i*3),recentTrend:0,minuteTrend:0,factors:{defense:1,pace:1},eligible:true,team:i%2?'AAA':'BBB',match:{id:'game'},residuals:forecast.residuals}));
const before=rows.map(p=>p.expected),ownership=estimateOwnership(rows,'2026-11-24',optimize,{samples:18});
assert.deepEqual(rows.map(p=>p.expected),before,'ownership must never change point predictions');
assert.ok(Math.abs(rows.reduce((s,p)=>s+p.predictedOwnership,0)-500)<1e-8);
assert.ok(rows.reduce((s,p)=>s+p.predictedOwnership*p.energy/100,0)<=150+1e-8);
for(const ids of ownership.portfolios){const a=rows.filter(p=>ids.includes(p.id));assert.equal(a.length,5);assert.ok([2,3].includes(a.filter(p=>p.position==='front').length));}
const base=rows[0];assert.ok(ownershipSignal({...base,recentTrend:10},'2026-11-24').form>ownershipSignal(base,'2026-11-24').form);
const model={rows,ownership:{profiles:ownership.profiles}};
const survival=survivalRecommendation(model,optimize,{training:25,validation:40});
assert.equal(survival.lineup.length,5);assert.equal(survival.validation.scenarios.length,9);
assert.ok(survival.validation.scenarios.every(s=>s.risk>=0&&s.risk<=1));
const constrained=survivalRecommendation(model,optimize,{exclude:[survival.lineup[0]],training:5,validation:5});
assert.ok(!constrained.lineup.includes(survival.lineup[0]));
assert.deepEqual(survivalRecommendation(model,optimize,{lock:['missing'],training:1,validation:1}).lineup,[]);
const tiedRows=rows.slice(0,3).concat(rows.slice(6,8));
const tiedOwnership=estimateOwnership(tiedRows,'2026-11-24',optimize,{samples:2});
const tied=survivalRecommendation({rows:tiedRows,ownership:tiedOwnership},optimize,{training:3,validation:3});
for(const scenario of tied.validation.scenarios)assert.ok(Math.abs(scenario.risk-4/scenario.remaining)<1e-10,'identical portfolios must lose only through the declared random tiebreak');
console.log('PASS: recency, weighted variance, effective samples, sparse data, ownership feasibility, mean separation, legal survival lineups and restrictions.');
